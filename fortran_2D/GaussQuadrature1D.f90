  ! -------------------------------------------------------
  ! Integrate f(x) over [xa, xb]
  ! -------------------------------------------------------
  real(8) function integrate(obj, xa, xb, f)
    type(GaussQuadrature1D_t), intent(in) :: obj
    real(8),                 intent(in) :: xa, xb
    procedure(integrand_func)           :: f

    integer :: k
    real(8) :: C0, C1, x

    C0 = 0.5_8 * (xb - xa)
    C1 = 0.5_8 * (xb + xa)

    integrate = 0.0_8
    do k = 1, obj%nGauss
      x = C0 * obj%xGauss(k) + C1
      integrate = integrate + obj%wGauss(k) * f(x)
    end do
    integrate = integrate * C0

  end function integrate

